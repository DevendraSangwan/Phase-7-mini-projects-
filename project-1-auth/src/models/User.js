const mongoose = require('mongoose');

const userSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, trim: true, maxlength: 100 },
    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
      maxlength: 254
    },
    passwordHash: { type: String, required: true, select: false }
  },
  { timestamps: true, collection: 'Mini project 1' }
);

module.exports = mongoose.model('MiniProjectOneUser', userSchema);
